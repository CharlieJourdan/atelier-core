export type CloneKey = keyof typeof frClone

/** A line of the screens: `{name}` placeholders replaced. An unknown key shows itself (a visible hole, never a crash). */
export function tc(key: string, vars?: Record<string, string | number>): string {
  const raw: string = (frClone as Record<string, string>)[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}

/** `clone.…` keys carried by artefacts (proposal titles, summaries) are translated; any other text is the channel's own. */
export function tx(text: string, vars?: Record<string, string | number>): string {
  if (text.startsWith('clone.proposal.slot:')) return tc('clone.proposal.slot', { slot: text.slice('clone.proposal.slot:'.length), ...vars })
  return text.startsWith('clone.') ? tc(text, vars) : text
}
